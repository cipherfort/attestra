"""Render the generated reference pages, so they can never drift from the code:

    docs/reference/settings.md  from backend/src/aap/settings.py (MAPPING) + schemas/settings/aap.schema.json
    docs/reference/api.md       from schemas/api/openapi.yaml

    python3 tools/docs/render_reference.py           # write
    python3 tools/docs/render_reference.py --check   # CI: fail if a page is stale
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
HEADER = "<!-- GENERATED by tools/docs/render_reference.py — do not edit by hand -->\n"


def _mapping() -> dict[str, str]:
    tree = ast.parse((ROOT / "backend/src/aap/settings.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "MAPPING":
            return dict(ast.literal_eval(node.value))
    raise SystemExit("MAPPING not found in settings.py")


def _schema_node(schema: dict, dotted: str) -> dict:
    node = schema
    for part in dotted.split("."):
        node = (node.get("properties") or {}).get(part) or {}
    return node


def settings_page() -> str:
    schema = json.loads((ROOT / "schemas/settings/aap.schema.json").read_text())
    lines = [HEADER, "# Settings reference (`aap.yaml`)", "",
             "Every setting maps to one environment variable; a variable already set wins over the file. The file holds no",
             "secrets: credentials come from the secret store (`aap secrets put`, Kubernetes secrets, Key Vault).", "",
             "| `aap.yaml` key | Environment variable | Allowed values |", "|---|---|---|"]
    for key, env in _mapping().items():
        node = _schema_node(schema, key)
        allowed = (" / ".join(f"`{v}`" for v in node["enum"]) if "enum" in node
                   else f"pattern `{node['pattern']}`" if "pattern" in node
                   else node.get("type", "") if isinstance(node.get("type"), str) else "")
        desc = node.get("description", "")
        lines.append(f"| `{key}` | `{env}` | {allowed}{' — ' + desc if desc else ''} |")
    return "\n".join(lines) + "\n"


def api_page() -> str:
    spec = yaml.safe_load((ROOT / "schemas/api/openapi.yaml").read_text())
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            by_tag.setdefault((op.get("tags") or ["Other"])[0], []).append((method.upper(), path, op))
    lines = [HEADER, f"# API reference ({spec['info'].get('version', '')})", "",
             f"Base path `/api/v1`. The contract is [`schemas/api/openapi.yaml`](../../schemas/api/openapi.yaml); this page is",
             "rendered from it. Operations marked *designed* are in the contract but not implemented yet (they return 404).",
             "Errors are `application/problem+json`. Out-of-scope objects return 404, never 403 (no enumeration).", ""]
    for tag in sorted(by_tag):
        lines += [f"## {tag}", "", "| Operation | Request | Permission | Summary |", "|---|---|---|---|"]
        for method, path, op in sorted(by_tag[tag], key=lambda t: (t[1], t[0])):
            status = " *(designed)*" if op.get("x-status") == "designed" else ""
            summary = (op.get("summary") or op.get("description") or "").split("\n")[0].replace("|", "\\|")
            lines.append(f"| `{op['operationId']}`{status} | `{method} {path}` | `{op.get('x-permission', '')}` | {summary} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    pages = {ROOT / "docs/reference/settings.md": settings_page(), ROOT / "docs/reference/api.md": api_page()}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in pages.items() if not p.exists() or p.read_text() != text]
        if stale:
            print(f"ERROR stale generated docs: {', '.join(stale)}; run tools/docs/render_reference.py")
            return 1
        print("OK generated reference pages are current")
        return 0
    for path, text in pages.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
