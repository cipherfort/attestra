"""Build catalogue/frameworks/asvs-<version>-requirements.yaml from the OFFICIAL OWASP ASVS release file.

    gh release download v5.0.0_release -R OWASP/ASVS -p "*_en.flat.json"
    python3 tools/catalogue/import_asvs.py OWASP_Application_Security_Verification_Standard_5.0.0_en.flat.json

Only identifiers, chapter/section ids and levels are kept (no requirement text): enough to count applicable and
verified requirements. The output is a derived work of OWASP ASVS (CC BY-SA 4.0) and says so in its header.
Never hand-edit the output: re-run this script on a new official release.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main(path: str) -> int:
    raw = Path(path).read_bytes()
    reqs = json.loads(raw)["requirements"]
    m = re.search(r"(\d+\.\d+\.\d+)", Path(path).name)
    if not m:
        print("cannot read the ASVS version from the file name", file=sys.stderr)
        return 2
    version = m.group(1)
    lines = [
        f"# OWASP ASVS {version}: requirement index (ids and levels only), generated by tools/catalogue/import_asvs.py.",
        f"# Source: {Path(path).name} (official OWASP/ASVS release), sha256 {hashlib.sha256(raw).hexdigest()}.",
        "# Derived from the OWASP Application Security Verification Standard, (c) OWASP Foundation,",
        "# licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This file is CC BY-SA 4.0 too.",
        "# Do not edit by hand.",
        f'asvs_version: "{version}"',
        f"count: {len(reqs)}",
        "requirements:",
    ]
    for r in sorted(reqs, key=lambda r: [int(x) for x in r["req_id"][1:].split(".")]):
        if not re.match(r"^V\d+\.\d+\.\d+$", r["req_id"]) or str(r["L"]) not in ("1", "2", "3"):
            print(f"unexpected record {r.get('req_id')!r}", file=sys.stderr)
            return 1
        lines.append(f"  - {{ id: {r['req_id']}, chapter: {r['chapter_id']}, level: {r['L']} }}")
    out = ROOT / "catalogue" / "frameworks" / f"asvs-{version}-requirements.yaml"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(reqs)} requirements")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
